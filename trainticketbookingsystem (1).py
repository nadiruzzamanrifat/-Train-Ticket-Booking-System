import streamlit as st
import sqlite3
import pandas as pd

def child_fare(quantity):
    return quantity * 10

def adult_fare(quantity):
    return quantity * 25

def senior_fare(quantity):
    return quantity * 15

def total_fare(child, adult, senior):
    return child_fare(child) + adult_fare(adult) + senior_fare(senior)

conn = sqlite3.connect("bookings.db")
conn.execute("""
CREATE TABLE IF NOT EXISTS bookings (
id INTEGER PRIMARY KEY AUTOINCREMENT,
customer_name TEXT,
child_tickets INTEGER,
adult_tickets INTEGER,
senior_tickets INTEGER,
total_fare REAL
)
""")
conn.commit()
conn.close()

def save_booking(name, child, adult, senior, total):
    conn = sqlite3.connect("bookings.db")
    conn.execute("""
    INSERT INTO bookings
    (customer_name, child_tickets, adult_tickets,
    senior_tickets, total_fare)
    VALUES (?, ?, ?, ?, ?)
    """, (name, child, adult, senior, total))
    conn.commit()
    conn.close()

def view_bookings():
    conn = sqlite3.connect("bookings.db")
    data = pd.read_sql_query("SELECT * FROM bookings", conn)
    conn.close()
    return data

st.title("Train Ticket Booking System")
st.write("Child: £10 | Adult: £25 | Senior: £15")
name = st.text_input("Customer Name")
child = st.number_input("Child Tickets", min_value=0, step=1)
adult = st.number_input("Adult Tickets", min_value=0, step=1)
senior = st.number_input("Senior Tickets", min_value=0, step=1)
total = total_fare(child, adult, senior)
st.subheader(f"Total Fare: £{total:.2f}")
if st.button("Book Tickets"):
    if not name.strip():
        st.error("Please enter your name.")
    elif total == 0:
        st.error("Please select at least one ticket.")
    else:
        save_booking(name, child, adult, senior, total)
        st.success("Booking saved successfully!")
if st.button("View Bookings"):
    st.subheader("Booking Records")
    st.dataframe(view_bookings())
